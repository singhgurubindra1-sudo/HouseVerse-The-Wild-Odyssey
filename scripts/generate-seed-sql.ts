/**
 * Writes supabase/seed.sql from the same seed data that demo mode uses.
 * Run with: npm run seed:sql
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { buildSeed, DEFAULT_BADGES } from "../lib/seed";
import { HOUSE_ART, HOUSE_SEED } from "../lib/houses";

const q = (v: string | null | undefined) => (v === null || v === undefined ? "null" : `'${v.replace(/'/g, "''")}'`);
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const ago = (min: number) => `now() - interval '${Math.round(min)} minutes'`;

const seed = buildSeed();
const out: string[] = [
  "-- Wildlands seed data (generated by scripts/generate-seed-sql.ts). Run after schema.sql.",
  "-- Run it once when setting up. Running it again resets quests, forests, submissions and the demo members.",
  "begin;",
  "",
  "delete from public.activity_log; delete from public.member_badges; delete from public.forest_items;",
  "delete from public.submissions; delete from public.quests; delete from public.lore_cards;",
  "delete from public.trivia_questions; delete from public.badges;",
  `delete from public.profiles where id in (${seed.profiles.map((p) => q(p.id)).join(", ")});`,
  "",
];

for (const h of HOUSE_SEED) {
  out.push(
    `insert into public.houses (id, name, place, region, landscape, legendary, legendary_emoji, mascot, mascot_emoji, motto, lore, "values", leaders, color_primary, color_accent, tree_kinds, total_seeds) values (` +
      [q(h.id), q(h.name), q(h.place), q(h.region), q(h.landscape), q(h.legendary), q(h.legendaryEmoji), q(h.mascot), q(h.mascotEmoji), q(h.motto), q(h.lore), j(h.values), j(h.leaders), q(h.colorPrimary), q(h.colorAccent), j(HOUSE_ART[h.id].trees), seed.houseSeeds[h.id] ?? 0].join(", ") +
      `) on conflict (id) do update set name = excluded.name, place = excluded.place, region = excluded.region, landscape = excluded.landscape, legendary = excluded.legendary, legendary_emoji = excluded.legendary_emoji, mascot = excluded.mascot, mascot_emoji = excluded.mascot_emoji, motto = excluded.motto, lore = excluded.lore, "values" = excluded."values", leaders = excluded.leaders, color_primary = excluded.color_primary, color_accent = excluded.color_accent, tree_kinds = excluded.tree_kinds, total_seeds = excluded.total_seeds;`,
  );
}
// Real members who signed up keep their Seeds; add them back onto the house totals.
out.push("update public.houses h set total_seeds = h.total_seeds + coalesce((select sum(total_seeds) from public.profiles p where p.house_id = h.id), 0);");
out.push("");

for (const b of DEFAULT_BADGES) {
  out.push(`insert into public.badges (id, name, icon, description, rule) values (${q(b.id)}, ${q(b.name)}, ${q(b.icon)}, ${q(b.description)}, ${j(b.rule)});`);
}
out.push("");

for (const p of seed.profiles) {
  out.push(
    `insert into public.profiles (id, name, handle, house_id, role, total_seeds, onboarded, created_at) values (${q(p.id)}, ${q(p.name)}, ${q(p.handle)}, ${q(p.houseId)}, ${q(p.role)}, ${seed.profileSeeds[p.id] ?? 0}, true, ${ago(p.agoMin)});`,
  );
}
out.push("");

for (const x of seed.quests) {
  out.push(
    `insert into public.quests (id, title, description, track, seeds, starts_at, ends_at, house_id, active, created_at) values (${q(x.id)}, ${q(x.title)}, ${q(x.description)}, ${q(x.track)}, ${x.seeds}, ${ago(x.startsAgoMin)}, ${ago(-x.endsInMin)}, ${q(x.houseId)}, ${x.active}, ${ago(x.startsAgoMin)});`,
  );
}
out.push("");

for (const s of seed.submissions) {
  out.push(
    `insert into public.submissions (id, member_id, quest_id, house_id, proof_url, proof_text, status, reviewed_by, note, created_at, reviewed_at) values (${q(s.id)}, ${q(s.memberId)}, ${q(s.questId)}, ${q(s.houseId)}, ${q(s.proofUrl)}, ${q(s.proofText)}, ${q(s.status)}, ${q(s.reviewedBy)}, ${q(s.note)}, ${ago(s.agoMin)}, ${s.reviewedAgoMin === null ? "null" : ago(s.reviewedAgoMin)});`,
  );
}
out.push("");

const questOf = new Map(seed.submissions.map((s) => [s.id, s.questId]));
for (const f of seed.forestItems) {
  out.push(
    `insert into public.forest_items (id, house_id, kind, x, y, planted_by, submission_id, quest_id, source, label, track, seeds, created_at) values (${q(f.id)}, ${q(f.houseId)}, ${q(f.kind)}, ${f.x}, ${f.y}, ${q(f.plantedBy)}, ${q(f.submissionId)}, ${q(f.submissionId ? questOf.get(f.submissionId) ?? null : null)}, ${q(f.source)}, ${q(f.label)}, ${q(f.track)}, ${f.seeds}, ${ago(f.agoMin)});`,
  );
}
out.push("");

for (const m of seed.memberBadges) {
  out.push(`insert into public.member_badges (member_id, badge_id, earned_at) values (${q(m.memberId)}, ${q(m.badgeId)}, ${ago(m.agoMin)});`);
}
out.push("");

for (const l of seed.lore) {
  out.push(`insert into public.lore_cards (id, house_id, position, title, body, emoji) values (${q(l.id)}, ${q(l.houseId)}, ${l.position}, ${q(l.title)}, ${q(l.body)}, ${q(l.emoji)});`);
}
for (const t of seed.trivia) {
  out.push(
    `insert into public.trivia_questions (id, house_id, position, question, options, answer_index) values (${q(t.id)}, ${q(t.houseId)}, ${t.position}, ${q(t.question)}, ${j(t.options)}, ${t.answerIndex});`,
  );
}
out.push("");

for (const a of seed.activity) {
  out.push(`insert into public.activity_log (id, actor_id, action, details, house_id, created_at) values (${q(a.id)}, ${q(a.actorId)}, ${q(a.action)}, ${q(a.details)}, ${q(a.houseId)}, ${ago(a.agoMin)});`);
}

out.push("", "commit;", "");
writeFileSync(join(__dirname, "..", "supabase", "seed.sql"), out.join("\n"));
console.log("Wrote supabase/seed.sql");
